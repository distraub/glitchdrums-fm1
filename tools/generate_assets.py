#!/usr/bin/env python3
"""Generate integer tables and RGB565 themes from GlitchDrums' source vocabulary.
No floating point or table construction runs on the FM-1 audio thread.
"""
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
def array(name, values, kind='int16_t'):
    values = list(values)
    lines = [', '.join(map(str, values[i:i+16])) for i in range(0, len(values), 16)]
    return f'static const {kind} {name}[{len(values)}] = {{\n' + ',\n'.join(lines) + '\n};\n'

def main():
    s = (REPO / 'GlitchDrumsExtension/UI/GlitchDrumsTheme.swift').read_text()
    names = dict(re.findall(r'case \.(\w+): "([^"]+)"', s))
    palettes = {}
    order = re.findall(r'case (\w+) = \d+', s)
    dark = [(0.15,.17,.20),(.76,.80,.85),(.02,.04,.06),(.05,.06,.08),(.46,.51,.57)]
    for name in order:
        line = re.search(r'case \.' + name + r': (.+)', s[s.index('private var colors'):]).group(1)
        if 'swapping' in line:
            base = re.search(r'GlitchDrumsTheme\.(\w+)\.colors', line).group(1)
            p = palettes[base].copy(); p[0], p[1] = p[1], p[0]
        else:
            p = [tuple(map(float, x.split(','))) for x in re.findall(r'\.rgb\(([^)]+)\)', line)]
            if '.dark(' in line: p += dark
        assert len(p) == 7
        palettes[name] = p
    def rgb(c):
        r,g,b = [round(v*255) for v in c]
        return ((r>>3)<<11) | ((g>>2)<<5) | (b>>3)
    text = '/* Generated by tools/generate_assets.py from GlitchDrumsTheme.swift. */\n'
    text += '#pragma once\n#include <stdint.h>\n'
    text += 'typedef struct { const char *name; uint16_t accent, alt, surface, text, inverse, bg, chrome; } GDTheme;\n'
    text += 'static const GDTheme gd_themes[] = {\n'
    for name in order:
        text += '{"' + names[name] + '", ' + ','.join(hex(rgb(c)) for c in palettes[name]) + '},\n'
    text += '};\n#define GD_THEME_COUNT 38\n'
    (ROOT / 'src/themes.h').write_text(text)
    # Original synthetic material formulas from GlitchVoice.hpp, quantized offline.
    # Digital tape retains the phase-continuous carrier schedule; no source audio.
    tables = [[] for _ in range(8)]
    noise = []; seed=0x7a91b23d; low=high=dustlow=0.; phase=0.
    carriers=[44,52,44,52,60,52,68,44,52,68,60,44,68,60,52,60]
    levels=[.84,1,.84,1,.92,1,.76,.90,1,.78,.92,.86,.76,.94,1,.90]
    for i in range(4096):
        t=i/4096; sec=i/48000; tau=math.tau
        seed ^= (seed<<13)&0xffffffff; seed ^= seed>>17; seed ^= (seed<<5)&0xffffffff
        n=(seed/4294967295)*2-1; noise.append(n)
        low += .55*(n-low); high += .055*(n-high); dustlow += .12*(n-dustlow)
        tables[0].append(.52*math.sin(tau*8*t+1.7*math.sin(tau*3*t))+.24*math.sin(tau*19*t)+.14*math.sin(tau*43*t)+.2*math.exp(-t*35)*math.sin(tau*137*t))
        body=.52*math.sin(tau*(165*sec+1.1*(1-math.exp(-sec/.004))))*math.exp(-sec/.030)
        ring=(.17*math.sin(tau*731*sec)+.11*math.sin(tau*1283*sec))*math.exp(-sec/.024)
        grit=1.15*(low-high)*(.72*math.exp(-sec/.014)+.28*math.exp(-sec/.055))
        tables[1].append((1-math.exp(-sec/.00025))*(body+ring+grit))
        tables[2].append((.68+.32*math.sin(tau*5*t))*(.48*math.sin(tau*37*t)+.30*math.sin(tau*91*t+.7)+.18*math.sin(tau*173*t+1.4)))
        tables[3].append(.62*math.sin(tau*5*t)+.25*math.sin(tau*10*t+.2)+.11*math.sin(tau*15*t+.5))
        tables[4].append((1 if i%173<19 else .28)*(.72*dustlow+.28*n))
        tables[5].append(.70*math.sin(tau*6*t)-.46*math.sin(tau*12*t)+.20*math.sin(tau*18*t+.4))
        sym=i//256; nxt=(sym+1)%16; a=max(0,min(1,(i%256/256-.78)/.22)); a=a*a*(3-2*a)
        cycles=carriers[sym]+a*(carriers[nxt]-carriers[sym]); level=levels[sym]+a*(levels[nxt]-levels[sym])
        tables[6].append(level*(.9*math.sin(phase)+.1*math.sin(2*phase+.35))); phase += tau*cycles/4096
        tables[7].append(.36*math.sin(tau*11*t)+math.exp(-(t*8%1)*16)*(.34*math.sin(tau*89*t)+.22*math.sin(tau*211*t+.8)))
    text='/* Generated integer DSP assets; see tools/generate_assets.py. */\n#pragma once\n#include <stdint.h>\n'
    for j, table in enumerate(tables+[noise]):
        mean=sum(table)/4096; peak=max(abs(x-mean) for x in table)
        text += array('gd_tape_'+str(j), (round((x-mean)/peak*28000) for x in table))
    text += 'static const int16_t *const gd_tapes[9] = {' + ','.join('gd_tape_'+str(j) for j in range(9)) + '};\n'
    text += array('gd_note_inc', (round(440*2**((i-69)/12)*2**32/44100) for i in range(128)), 'uint32_t')
    text += array('gd_sines', (round(math.sin(math.tau*i/2048)*32767) for i in range(2048)))
    times=[.0005*(32000**(i/127)) for i in range(128)]
    text += array('gd_time_frames', (max(1,round(t*44100)) for t in times),'uint32_t')
    text += array('gd_decay_coeff', (round(math.exp(math.log(.0001)/(t*44100))*2**30) for t in times),'uint32_t')
    text += array('gd_cutoff_hz',(round(20*900**(i/127)) for i in range(128)),'uint16_t')
    text += array('gd_loop_size',(round(32*128**(i/127)) for i in range(128)),'uint16_t')
    (ROOT/'src/tables.h').write_text(text)
    print('Generated 38 themes, 8 materials, noise, pitch, envelopes and filter tables.')

if __name__=='__main__': main()
