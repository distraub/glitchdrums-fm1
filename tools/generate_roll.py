#!/usr/bin/env python3
"""Continuous Glitch rates with tempo-aware capture limits and legacy migration."""
import math
from pathlib import Path
rows=[]
for fold in range(3):
 base=4<<fold;octaves=7-fold
 values=[0]+[round(base*2**((q-1)*octaves/126)*65536) for q in range(1,128)]
 for octave in range(octaves+1):values[1+round(octave*126/octaves)]=(base<<octave)*65536
 assert all(a<b for a,b in zip(values,values[1:]));rows.append(values)
old=[0]+[round(32*2**((q-1)*5/126)*65536) for q in range(1,128)]
for q,division in [(1,32),(26,64),(51,128),(77,256),(102,512),(127,1024)]:old[q]=division*65536
migration=[[0]+[min(range(1,128),key=lambda q:abs(math.log(row[q]/old[rate]))) for rate in range(1,128)] for row in rows]
def array(name,values,typ):
 return 'static const '+typ+' '+name+'[3][128]={'+','.join('{'+','.join(map(str,row))+'}' for row in values)+'};\n'
s='/* Generated by tools/generate_roll.py. */\n#pragma once\n#define GD_GLITCH_FRAMES 32768u\n#define GD_GLITCH_MASK (GD_GLITCH_FRAMES-1u)\n'
s+=array('gd_roll_division',rows,'uint32_t')+array('gd_glitch_migrate6',migration,'uint8_t')
s+='''static inline unsigned gd_glitch_range(unsigned bpm){unsigned fold=0;while(fold<2&&(uint64_t)44100u*60u>(uint64_t)bpm*(GD_GLITCH_FRAMES-1u)*(1u<<fold))++fold;return fold;}
static inline unsigned gd_previous_glitch_rate(unsigned rate,unsigned bpm){return gd_glitch_migrate6[gd_glitch_range(bpm)][rate<128?rate:0];}
static inline unsigned gd_old_roll_rate(unsigned rate,unsigned bpm){static const uint8_t old[5]={0,1,26,51,77};return gd_previous_glitch_rate(rate<5?old[rate]:0,bpm);}
static inline unsigned gd_glitch_key_rate(unsigned key){return 1+((key>15?15:key)*126+7)/15;}
'''
(Path(__file__).resolve().parents[1]/'src/roll_tables.h').write_text(s)
