#!/usr/bin/env python3
"""Compile the app's real Swift catalog, map its first 8 sounds per FM1 lane.
Generated C contains control bytes only; no target floating point or samples.
Uses the existing INIT-calibrated physical lookup tables, including detents.
"""
import hashlib,json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];REPO=ROOT.parents[1]
BUILD=ROOT/'build/native';BUILD.mkdir(parents=True,exist_ok=True)
files=['DrumPadModel','PadParameter','GlitchParameterDescriptor','GlitchRoutingState','VoiceEditImage','VoiceEditParameterCatalog','VoicePreset','VoicePresetParameterCatalog','FactoryVoicePreset','FactoryVoicePresetCatalog']
source=[REPO/'GlitchDrumsExtension/Model'/f'{f}.swift' for f in files]
exe=BUILD/'export-factory';raw=BUILD/'app-factory.json'
subprocess.run(['swiftc','-module-cache-path','/private/tmp/gd-swift-module-cache',*map(str,source),str(ROOT/'tools/export_factory.swift'),'-o',str(exe)],check=True)
subprocess.run([str(exe),str(raw)],check=True)
app=json.loads(raw.read_text())
def table(file,name):
 text=(ROOT/'src'/file).read_text();body=re.search(r'\b'+name+r'\[[^=]+?=\s*(\{.*?\});',text,re.S).group(1)
 return json.loads(body.replace('{','[').replace('}',']'))
def scale(unit):return {'cents':100,'frames':44100,'q15':32768,'integer':1}[unit]
ac=json.loads((ROOT/'docs/ACOUSTIC_INIT.json').read_text());sy=json.loads((ROOT/'docs/SYNTH_INIT.json').read_text());ki=json.loads((ROOT/'docs/KICK_INIT.json').read_text())
units=table('acoustic_tables.h','gd_ac_units');levels=table('acoustic_tables.h','gd_ac_level')
synthlevels=table('synth_tables.h','gd_synth_level')
models=['kick','snare','closedHat','openHat','clap','percussion','glitch','analog']
metadata=[]
for lane,model in enumerate(models):
 if lane==0:
  fields=[k for k in ki['init'] if k not in ['level','noise']]
  scales=[44100 if i in [1,5,7,8,10,12,13] else 100 if i==0 else 256 if i==4 else 32768 for i in range(16)]
  metadata.append((fields,table('kick_init.h','gd_kick_units'),scales,table('kick_init.h','gd_kick_level'),ki['init']))
 elif lane==5:
  a=json.loads((ROOT/'docs/PERC_INIT.json').read_text());metadata.append((a['fields'],table('perc_tables.h','gd_perc_units'),[scale(u) for u in a['units']],table('perc_tables.h','gd_perc_level'),a['init']))
 elif lane<6:
  a=ac[lane-1];metadata.append((a['fields'],units[lane-1],[scale(u) for u in a['units']],levels[lane-1],a['init']))
 else:
  key='glitch' if lane==6 else 'analog';a=sy[key];fields=a['fields'];scales=[]
  for i in range(29):
   freq=(lane==7 and i==9)or(lane==6 and i==12)
   note=(lane==7 and i in [0,1,24])or(lane==6 and i in [3,23])
   time=(lane==7 and i in [15,20,23,26])or(lane==6 and i in [16,17,18,19])
   choice=(lane==7 and i in [2,3,27])or(lane==6 and i in [0,1,2,14,20,21,22])
   scales.append(1 if freq or choice else 100 if note else 44100 if time else 32768)
  metadata.append((fields,table('synth_tables.h','gd_gl_units' if lane==6 else 'gd_an_units'),scales,synthlevels[lane-6],a['init']))
records=[];names=[];banks=[]
for lane,model in enumerate(models):
 fields,rows,scales,levelrow,init=metadata[lane];lane_names=[];bank=[]
 for patch in [p for p in app if p['model']==model and p['slot']<=7]:
  values=patch['parameters'];codes=[];mapped=[]
  for i,(field,row,s) in enumerate(zip(fields,rows,scales)):
   value=values.get(field,init[field] if field in init else 0)
   maximum=108 if lane==6 and i in [3,23] else 96 if lane==7 and i in [0,1] else 2 if lane==6 and i in [0,20] else 7 if lane==6 and i in [1,21] else 1 if lane==6 and i in [2,22] else 3 if lane==6 and i==14 else 1 if lane==7 and i in [2,3,27] else 3 if field=='clapBursts' else 1 if field=='tomType' else 0 if field=='unused' or (field=='hatChokeTime' and model=='closedHat') else 127
   q=min(range(maximum+1),key=lambda q:abs(row[q]/s-value));codes.append(q)
   mapped.append(dict(parameter=field,requested=value,encoded=row[q]/s,code=q))
  level=min(range(128),key=lambda q:abs(levelrow[q]/32768-patch['level']))
  # Deep voice fields are followed by LEVEL at index 29; unused slots stay
  # zero and are deliberately not invented from the old macro recipes.
  image=codes+[0]*(29-len(codes))+[level]
  assert len(image)==30
  lane_names.append(patch['name']);bank.append(image)
  records.append(dict(lane=lane,model=model,slot=patch['slot']+1,source_slot=patch['slot'],name=patch['name'],level=patch['level'],level_byte=level,control_bytes=image,mapping=mapped))
 names.append(["INIT"]+lane_names);banks.append(bank)
assert len(records)==56 and all(len(b)==7 for b in banks)
def c(a):return '{'+','.join(c(x) if isinstance(x,list) else json.dumps(x) for x in a)+'}'
out='/* Generated by tools/generate_factory.py from the compiled app catalog. */\n#pragma once\n'
out+='static const char *const gd_factory_voice_names[8][8]='+c(names)+';\n'
out+='static const uint8_t gd_factory_voice_bytes[8][7][30]='+c(banks)+';\n'
(ROOT/'src/factory_voices.h').write_text(out)
(ROOT/'docs/FACTORY_VOICES.json').write_text(json.dumps(dict(source_sha256={str(p.relative_to(REPO)):hashlib.sha256(p.read_bytes()).hexdigest() for p in source},presets=records),indent=2)+'\n')
summary=['# App factory voices on FM-1','',
 'F1 is INIT for every lane. F2–F8 follow the first seven named app presets.',
 'INIT remains the startup sound and ORIGINAL kit. In VOICE PRESETS, hold ENV',
 'and press SEL as an additional INIT shortcut. ARP compares it.',
 '', '| Lane | F1 → F8 |', '|---|---|']
for model,bank in zip(models,names):summary.append('| '+model+' | '+' · '.join(bank)+' |')
summary += ['', 'Generated by compiling FactoryVoicePresetCatalog.swift, then selecting the',
 'nearest existing INIT-calibrated control detents. Physical requested/encoded',
 'values and source hashes are in FACTORY_VOICES.json. This is 7-bit parameter',
 'quantization, not a bit-identical floating-point DSP port. PERC replaces TOM',
 'in firmware 0.14.0. Low/High Tom do not have dedicated FM-1 lanes.',
 '', 'Voice recall keeps the arrangement and other lanes. It includes the source',
 'preset level; firmware sound presets also reset their own pan/transpose/LFOs',
 'to the INIT sound values. The eight user slots remain separate and writable.', '']
(ROOT/'docs/FACTORY_VOICES.md').write_text('\n'.join(summary))
print('Generated INIT plus 56 app factory voices in original order')
